def load_text(name: str) -> str:
    return (BOOK_DIR / name).read_text(encoding="utf-8", errors="ignore")


def clean_snip(s: str) -> str:
    s = re.sub(r"\s+", "", s)
    s = s.strip("，。！？；、:：\"“”‘’（）()[]【】 ")
    return s


def harvest(text: str, patterns: list[str], limit: int = 50) -> list[str]:
    out, seen = [], set()
    for pat in patterns:
        for m in re.finditer(pat, text):
            s = clean_snip(m.group(0))
            if not (4 <= len(s) <= 40):
                continue
            if any(bad in s for bad in ("http", "www", "【", "】")):
                continue
            if s in seen:
                continue
            seen.add(s)
            out.append(s)
            if len(out) >= limit:
                return out
    return out


def build_pairs(curated, buckets_data):
    pairs = []
    for c in curated:
        for a in c["ai"]:
            for h in c["human"]:
                pairs.append(
                    {
                        "category": c["category"],
                        "meaning": c["meaning"],
                        "ai_expr": a,
                        "human_expr": h,
                        "source": "curated",
                    }
                )
    for b in buckets_data:
        ai_sents = b["ai_examples"]
        hu_sents = b["human_examples"]
        # denser cross for short items
        for a in ai_sents[:12]:
            for h in hu_sents[:8]:
                if len(a) > 36 or len(h) > 28:
                    continue
                pairs.append(
                    {
                        "category": b["category"],
                        "meaning": b["meaning"],
                        "ai_expr": a,
                        "human_expr": h,
                        "source": "harvested",
                    }
                )
    # dedupe
    seen, uniq = set(), []
    for p in pairs:
        key = (p["ai_expr"], p["human_expr"])
        if key in seen:
            continue
        seen.add(key)
        uniq.append(p)
    return uniq


def main():
    by = defaultdict(list)
    for b in VERDICTS["books"]:
        by[b["verdict"]].append(b["file"])

    ai_side = by["ai"] + by["mixed"]
    human_side = by["human"]

    # larger corpus slices for richer harvest
    ai_corpus = "\n".join(load_text(f)[:120000] for f in ai_side)
    hu_corpus = "\n".join(load_text(f)[:120000] for f in human_side)

    bucket_rows = []
    for b in BUCKETS:
        ai_ex = harvest(ai_corpus, b["ai_patterns"], limit=45)
        hu_ex = harvest(hu_corpus, b["human_patterns"], limit=45)
        # if human harvest thin, also allow from mixed lightly? keep pure
        bucket_rows.append(
            {
                "id": b["id"],
                "category": b["category"],
                "meaning": b["meaning"],
                "ai_examples": ai_ex,
                "human_examples": hu_ex,
                "ai_count": len(ai_ex),
                "human_count": len(hu_ex),
            }
        )

    pairs = build_pairs(CURATED, bucket_rows)
    random.Random(7).shuffle(pairs)

    # curated-only map + all-pair map
    mapping = {}
    for p in pairs:
        if p["source"] != "curated" and not (4 <= len(p["ai_expr"]) <= 28 and 2 <= len(p["human_expr"]) <= 20):
            continue
        slot = mapping.setdefault(
            p["ai_expr"],
            {"category": p["category"], "meaning": p["meaning"], "replace_with": []},
        )
        if p["human_expr"] not in slot["replace_with"]:
            slot["replace_with"].append(p["human_expr"])

    # category index
    by_cat = defaultdict(list)
    for b in bucket_rows:
        by_cat[b["category"]].append(b["meaning"])
    for c in CURATED:
        if c["meaning"] not in by_cat[c["category"]]:
            by_cat[c["category"]].append(c["meaning"])

    bank = {
        "meta": {
            "purpose": "后期把偏AI/模板句替换成更口语的人味表达（扩充版）",
            "ai_source_books": ai_side,
            "human_source_books": human_side,
            "categories": {k: v for k, v in by_cat.items()},
            "note": "同义近义对照；替换时按语境改人称/时态，禁止无脑全局替换",
            "version": "2.0-expanded",
        },
        "buckets": bucket_rows,
        "curated_groups": CURATED,
        "replacement_pairs": pairs,
        "stats": {
            "bucket_count": len(bucket_rows),
            "curated_group_count": len(CURATED),
            "pair_count": len(pairs),
            "unique_ai_expr_in_map": len(mapping),
            "ai_source_count": len(ai_side),
            "human_source_count": len(human_side),
            "category_count": len(by_cat),
        },
    }

    (OUT / "ai_human_phrase_bank.json").write_text(
        json.dumps(bank, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    # slim replacements: curated first, then compact harvested
    slim_pairs = [p for p in pairs if p["source"] == "curated"]
    for p in pairs:
        if p["source"] != "harvested":
            continue
        if 4 <= len(p["ai_expr"]) <= 28 and 2 <= len(p["human_expr"]) <= 20:
            slim_pairs.append(p)

    slim = {
        "purpose": "AI/模板句 → 人味句 替换词典（扩充精简版）",
        "usage": "按 category/meaning 选组；替换后改人称语气；禁止无脑全局替换",
        "version": "2.0-expanded",
        "pair_count": len(slim_pairs),
        "unique_ai_expr": len(mapping),
        "categories": {k: v for k, v in by_cat.items()},
        "pairs": slim_pairs,
        "map": mapping,
        "buckets_summary": [
            {
                "id": b["id"],
                "category": b["category"],
                "meaning": b["meaning"],
                "ai_top": b["ai_examples"][:12],
                "human_top": b["human_examples"][:12],
            }
            for b in bucket_rows
        ],
    }
    (OUT / "ai_to_human_replacements.json").write_text(
        json.dumps(slim, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    # markdown index
    md = [
        "# AI ↔ 人工 语句对照库（扩充版）",
        "",
        f"- 语义桶：{len(bucket_rows)}",
        f"- 人工精选组：{len(CURATED)}",
        f"- 对照 pair：{len(pairs)}（精简替换词典 {len(slim_pairs)}）",
        f"- AI 表达键：{len(mapping)}",
        "",
        "## 分类索引",
        "",
    ]
    for cat, meanings in by_cat.items():
        md.append(f"### {cat}")
        for m in meanings:
            md.append(f"- {m}")
        md.append("")

    md.append("## 精选对照示例")
    md.append("")
    for c in CURATED:
        md.append(f"### [{c['category']}] {c['meaning']}")
        md.append("")
        md.append("| AI/模板 | 人味替代 |")
        md.append("|---|---|")
        for a, h in zip(c["ai"][:5], c["human"][:5]):
            md.append(f"| {a} | {h} |")
        md.append("")

    (OUT / "phrase_bank_index.md").write_text("\n".join(md), encoding="utf-8")

    print(json.dumps(bank["stats"], ensure_ascii=False, indent=2))
    print("categories:", list(by_cat.keys()))


if __name__ == "__main__":
    main()
