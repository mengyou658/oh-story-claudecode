def ch_file(n: int) -> Path:
    return OUT / f"细纲_第{n:03d}章.md"


def write_fine(
    n: int,
    title: str,
    core: str,
    stage: str,
    unit_id: str,
    beat: str,
    emotion: str,
    goal: str,
    pos: str,
    formula: str,
    hook_open: str,
    cool: str,
    price: str,
    loop: str,
    forbid: str,
    free: str,
    five: tuple[str, str, str, str, str],
    main_line: str,
    aux_line: str,
    logic: str,
    cast: str,
    lens: str,
    rel: str,
    pov: str,
    info_gap: str,
    beats: list[tuple[str, str, str, str]],
    end_set: str,
    hook_end: str,
    words: int = 2400,
) -> None:
    rows = "\n".join(
        f"| {i+1} | {a} | {b} | {c} | {d} |" for i, (a, b, c, d) in enumerate(beats)
    )
    text = f"""## 细纲（第 {n} 章）

### 第 {n} 章：{title}
- 核心事件：{core}
- 字数目标：{words} 字
- 字数口径：visible_chars_v1
- 阶段位置：{stage}
- 单元ID/位置：{unit_id}；{beat}
- 目标情绪：{emotion}
- 主角目标/关键选择：{goal}
- 章节定位：{pos}
- 本章结构公式：{formula}
- 章首钩子：{hook_open}
- 爽点：{cool}
- 本章标价：{price}
- 闭环状态：{loop}
- 本章禁止提前释放：{forbid}
- 写手自由区：{free}
- 契约风险：契约安全

#### 内容概括（五段式）
- 起因：{five[0]}
- 发展：{five[1]}
- 转折：{five[2]}
- 高潮：{five[3]}
- 结尾：{five[4]}

#### 情节安排（多线）
- 主线推进：{main_line}
- 辅线推进：{aux_line}
- 逻辑线：{logic}

#### 人物关系和出场顺序
- 出场顺序：{cast}
- 镜头准入：{lens}
- 人物关系变化：{rel}
- 视角/信息差：{pov}
- 信息差触发点：{info_gap}

#### 情节细化
| # | 情节点（谁做了什么） | 功能标签 | 分辨率 | 执行边界 |
|---|---|---|---|---|
{rows}

#### 结尾设定和钩子
- 结尾设定：{end_set}
- 章尾钩子：{hook_end}
"""
    ch_file(n).write_text(text, encoding="utf-8")


def expand_unit(
    start: int,
    end: int,
    unit_id: str,
    vol: int,
    stage_label: str,
    titles: list[str],
    cores: list[str],
    emotions: list[str],
    beats_fn,
    forbid_default: str,
    lines: tuple[str, str],
) -> None:
    assert end - start + 1 == len(titles) == len(cores) == len(emotions)
    n_chapters = end - start + 1
    for i, n in enumerate(range(start, end + 1)):
        beat_idx = i + 1
        pos = (
            "高压"
            if i in (n_chapters - 2, n_chapters // 2)
            else ("关系回收" if i % 4 == 1 else ("低压生活" if i == n_chapters - 1 and n_chapters > 5 else "推进"))
        )
        if i == 0:
            pos = "推进"
        title = titles[i]
        core = cores[i]
        emotion = emotions[i]
        beat = f"单元内第{beat_idx}拍/{beats_fn(i, n_chapters)}"
        head = core.split("；")[0].rstrip("。")
        goal = f"完成「{head}」相关抉择；守躺平、不出名、不接编制。"
        formula = f"{title}（局面） + 关键选择 + 缩影/私下手段 + 章尾新债"
        hook_open = f"承接钩 — {head}"
        cool_keys = ("结清", "抽", "杀价", "救", "渡", "短清", "暗护", "卸梢", "动手", "生还", "反制", "短胜")
        cool = (
            "私下短结算/信息差优越"
            if any(k in core for k in cool_keys)
            else "无显性爽点，功能是蓄压、关系或信息推进"
        )
        price = "暴露风险 / 命数库存 / 闺蜜安稳税"
        nxt = cores[min(i + 1, n_chapters - 1)].split("；")[0].rstrip("。")
        loop = f"获得：{head}。扣住下拍：{nxt}"
        forbid = forbid_default
        free = "对话语气；街景/副本细部；周晏一句反应；面板/暗账体感措辞"
        # five-act from core clauses
        parts = [p.strip() for p in core.replace("。", "；").split("；") if p.strip()]
        five = (
            parts[0] if parts else head,
            parts[1] if len(parts) > 1 else f"围绕「{title}」加压或推进",
            parts[2] if len(parts) > 2 else f"沈晚宁做出与「{title}」相关的取舍",
            parts[-1] if len(parts) > 1 else f"「{title}」落到可见结果",
            f"画面停在余波；钩向：{nxt}",
        )
        main_line, aux_line = lines
        logic = f"{head} → 行动 → 可见结果 → {nxt}"
        cast = "沈晚宁；周晏" + (
            "；特事局接口人" if any(k in core for k in ("特事", "交易", "接口", "交货", "杀价")) else ""
        ) + (
            "；路人/玩家/舆论" if any(k in core for k in ("群", "舆论", "世人", "论坛", "新闻")) else ""
        )
        lens = "双人为主；必要时远端文字/群聊/现场外围"
        rel = "周晏依赖或半知情加深；女主距离感/保护欲调整"
        pov = "女主主导；读者知暗账边界，场内人不知全貌"
        info_gap = (
            f"场内人按错误前提行动；读者记得：{head}"
            if i % 2 == 0
            else "只提醒库存/规矩/不出名，不新开大差"
        )
        beats = [
            (f"局面：{parts[0] if parts else head}", "铺垫", "中", "禁：越单元剧透。放：允许环境与体感一句"),
            (
                f"沈晚宁行动：{parts[1] if len(parts) > 1 else head}",
                "推进",
                "密",
                "禁：公开战力秀/当先锋/揭全价码。放：允许私下手段与杀价口吻",
            ),
            (
                f"场内反应：{parts[2] if len(parts) > 2 else '周晏或旁人可见反馈'}",
                "关系变化",
                "中",
                "禁：揭满级与命数课。放：允许差点漏嘴或错觉",
            ),
            (
                f"收束挂下一拍：{nxt}",
                "钩子承接",
                "疏",
                f"禁：{forbid.split('；')[0]}。放：允许远景一句",
            ),
        ]
        write_fine(
            n=n,
            title=title,
            core=core,
            stage=f"{stage_label}；第{vol}卷第{n}章",
            unit_id=unit_id,
            beat=beat,
            emotion=emotion,
            goal=goal,
            pos=pos,
            formula=formula,
            hook_open=hook_open,
            cool=cool,
            price=price,
            loop=loop,
            forbid=forbid,
            free=free,
            five=five,
            main_line=main_line,
            aux_line=aux_line,
            logic=logic,
            cast=cast,
            lens=lens,
            rel=rel,
            pov=pov,
            info_gap=info_gap,
            beats=beats,
            end_set=f"余波画面；未解：{nxt}",
            hook_end=f"悬念钩 — {nxt}；期待度：{'强' if i >= n_chapters - 2 else '中'}",
        )


